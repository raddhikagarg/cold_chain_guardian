function numericSensor({
  available = true,
  enabled = true,
  acceptable = null,
  warning = null,
  critical = null,
  escalationMinutes = null,
} = {}) {
  return {
    available,
    enabled: available && enabled,
    acceptable,
    warning,
    critical,
    escalationMinutes,
  }
}

function doorSensor({
  available = true,
  enabled = true,
  acceptableState = 'closed',
  warningOpenMinutes = null,
  criticalOpenMinutes = null,
} = {}) {
  return {
    available,
    enabled: available && enabled,
    acceptable: acceptableState ? { state: acceptableState } : null,
    warning:
      warningOpenMinutes != null ? { maxOpenMinutes: warningOpenMinutes } : null,
    critical:
      criticalOpenMinutes != null ? { maxOpenMinutes: criticalOpenMinutes } : null,
    escalationMinutes: 0,
  }
}

function noSensor() {
  return {
    available: false,
    enabled: false,
    acceptable: null,
    warning: null,
    critical: null,
    escalationMinutes: null,
  }
}

