/**
 * Build explicit per-sensor evidence for every fitted sensor. A sensor is
 * only shown as healthy when the record contains a recent self-test; missing
 * evidence deliberately stays Unknown in the device health helpers.
 */
function sensorEvidence(sensorIds, selfTestMinutesAgo, overrides = {}) {
  return sensorIds.reduce((entries, sensorId) => {
    entries[sensorId] = overrides[sensorId] ?? {
      status: 'ok',
      selfTestMinutesAgo,
      note: 'Self-test passed while the device was reporting.',
    }
    return entries
  }, {})
}

